-- Esquema PostgreSQL de referencia para el entregable técnico.
-- IMPORTANTE: únicamente ejecutar en una base VACÍA. No ejecutar sobre
-- la base ya creada con Alembic. Las migraciones del repositorio son
-- la fuente operativa de evolución de la BD.

BEGIN;

CREATE TABLE tariffs (
    id_tariff INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_market INTEGER NOT NULL,
    cdi INTEGER NULL,
    voltage_level INTEGER NOT NULL,
    "G" NUMERIC(18,8) NOT NULL,
    "T" NUMERIC(18,8) NOT NULL,
    "D" NUMERIC(18,8) NOT NULL,
    "R" NUMERIC(18,8) NOT NULL,
    "C" NUMERIC(18,8) NOT NULL,
    "P" NUMERIC(18,8) NOT NULL,
    "CU" NUMERIC(18,8) NOT NULL
);

-- Para el set de datos entregado, los voltajes 2/3 tienen CDI NULL.
-- Estas restricciones reflejan los índices del modelo compartido.
CREATE UNIQUE INDEX uq_tariffs_market_voltage_cdi
    ON tariffs (id_market, voltage_level, cdi) WHERE cdi IS NOT NULL;
CREATE UNIQUE INDEX uq_tariffs_market_voltage_no_cdi
    ON tariffs (id_market, voltage_level) WHERE cdi IS NULL;

CREATE TABLE xm_data_hourly_per_agent (
    record_timestamp TIMESTAMP WITHOUT TIME ZONE PRIMARY KEY,
    value NUMERIC(20,10) NOT NULL
);

CREATE TABLE services (
    id_service INTEGER PRIMARY KEY,
    id_market INTEGER NOT NULL,
    cdi INTEGER NOT NULL,
    voltage_level INTEGER NOT NULL
);

CREATE TABLE records (
    id_record INTEGER PRIMARY KEY,
    id_service INTEGER NOT NULL REFERENCES services(id_service),
    record_timestamp TIMESTAMP WITHOUT TIME ZONE NOT NULL
        REFERENCES xm_data_hourly_per_agent(record_timestamp),
    CONSTRAINT uq_records_service_timestamp UNIQUE (id_service, record_timestamp)
);
CREATE INDEX ix_records_id_service ON records (id_service);
CREATE INDEX ix_records_record_timestamp ON records (record_timestamp);

CREATE TABLE consumption (
    id_record INTEGER PRIMARY KEY REFERENCES records(id_record),
    value NUMERIC(18,6) NOT NULL,
    CONSTRAINT ck_consumption_value_nonnegative CHECK (value >= 0)
);

CREATE TABLE injection (
    id_record INTEGER PRIMARY KEY REFERENCES records(id_record),
    value NUMERIC(18,6) NOT NULL,
    CONSTRAINT ck_injection_value_nonnegative CHECK (value >= 0)
);

COMMIT;

